CATALOGS: dict[str, dict[str, str]] = {"pt_BR": PT_BR, "en": EN}
"""Available languages and their texts (same keys in every catalog)."""


def set_language(language: str) -> None:
    """Choose the language of every later text; raise ValueError for an unknown one."""
    global _language
    if language not in CATALOGS:
        raise ValueError("unknown language")
    _language = language


def language() -> str:
    """Return the active language code."""
    return _language


def t(key: str, /, count: int | None = None, **values: object) -> str:
    """Return the text for key in the active language, filled with values.

    With `count`, the key's `_one` or `_other` form is chosen and `{count}` is
    filled. Raise KeyError for a key missing from the catalog, so a typo fails
    in tests instead of showing a raw key to the user.
    """
    catalog = CATALOGS[_language]
    if count is not None:
        key = f"{key}_one" if count == 1 else f"{key}_other"
        values["count"] = count
    return catalog[key].format(**values)


# -- display formats (presentation only) --------------------------------------------

_CENT = Decimal("0.01")
_TENTH = Decimal("0.1")


def _separators() -> tuple[str, str]:
    """Return (thousands, decimal) separators of the active language."""
    return (".", ",") if _language == "pt_BR" else (",", ".")


def _swap(text: str) -> str:
    """Turn a '1,234.56' style number into the active language's separators."""
    thousands, decimal = _separators()
    return text.replace(",", "\0").replace(".", decimal).replace("\0", thousands)


def money(amount: Decimal | None) -> str:
    """Return an exact amount rounded half up to cents, e.g. 1.310,00 (— when None)."""
    if amount is None:
        return t("common.not_available")
    return _swap(f"{amount.quantize(_CENT, rounding=ROUND_HALF_UP):,.2f}")


def signed_money(amount: Decimal) -> str:
    """Return a money change with an explicit sign, never '-0,00'."""
    text = money(amount)
    return text if text.startswith("-") else f"+{text}"


def percent(ratio: Decimal | None, *, signed: bool = False) -> str:
    """Return a ratio as a percentage with one decimal, e.g. 84,4% (— when None)."""
    if ratio is None:
        return t("common.not_available")
    value = (ratio * 100).quantize(_TENTH, rounding=ROUND_HALF_UP)
    text = _swap(f"{value:,}") + "%"
    return f"+{text}" if signed and not text.startswith("-") else text


def decimal_number(value: float, *, signed: bool = False) -> str:
    """Return a statistical value with two decimals (never '-0,00')."""
    rounded = round(value, 2) + 0.0
    return _swap(f"{rounded:+,.2f}" if signed else f"{rounded:,.2f}")


def integer(value: int, *, signed: bool = False) -> str:
    """Return a whole number with thousands separators."""
    return _swap(f"{value:+,d}" if signed else f"{value:,d}")


def day(value: date) -> str:
    """Return a calendar date, e.g. 05/01/2026 (pt_BR) or 2026-01-05 (en)."""
    return value.strftime("%d/%m/%Y") if _language == "pt_BR" else value.isoformat()


def moment(value: datetime) -> str:
    """Return a date and time with its UTC offset when it has one."""
    text = value.strftime("%d/%m/%Y %H:%M:%S" if _language == "pt_BR" else "%Y-%m-%d %H:%M:%S")
    offset = value.strftime("%z")
    return f"{text} UTC{offset[:3]}:{offset[3:]}" if offset else text


def weekday(index: int) -> str:
    """Return the weekday name (0 = Monday)."""
    return t(f"weekday.{index}")


def method_title(key: str, fallback: str) -> str:
    """Return the translated title of a forecast method key (fallback for unknown keys)."""
    if key.startswith("moving_average_"):
        return t("method.moving_average", window=key.removeprefix("moving_average_"))
    try:
        return t(f"method.{key}")
    except KeyError:
        return fallback


def id_list(ids: tuple[str, ...] | list[str], limit: int = 5) -> str:
    """Return up to limit IDs separated by commas, then '…' when more were left out."""
    shown = ", ".join(ids[:limit])
    return f"{shown}, …" if len(ids) > limit else shown
